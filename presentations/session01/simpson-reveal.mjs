// Append to the existing local Session 1 introduction deck after the Cairo discussion.
// The caller reads data/raw/simpson_hotels.csv (created by scripts/fetch_data.py).
// Charts, their points and fitted lines remain editable in PowerPoint.
import { fitLine } from './ols-opening.mjs';

export function appendSimpsonReveal(presentation, applyPresentationChartFont, records) {
  const C = { ink: '#182C39', muted: '#546670', paper: '#FAF8F4',
    teal: '#087F82', orange: '#B54C22', blue: '#4363A8', axis: '#9CA6A9' };
  const source = 'https://www.frontiersin.org/journals/psychology/articles/10.3389/fpsyg.2013.00513/full';
  if (records.length !== 24 || new Set(records.map(r => r.hotel_id)).size !== 24) {
    throw Error('Expected the 24 distinct fictional hotels from make_simpson_hotels().');
  }
  const x = records.map(r => Number(r.distance_km));
  const y = records.map(r => Number(r.price_eur));
  if (![...x, ...y].every(Number.isFinite)) throw Error('Invalid numeric data.');
  const pooled = fitLine(x, y);
  const groups = ['A', 'B', 'C'].map((country, index) => {
    const rows = records.filter(r => r.country === country);
    if (rows.length !== 8) throw Error(`Expected eight hotels in country ${country}.`);
    const gx = rows.map(r => Number(r.distance_km));
    const gy = rows.map(r => Number(r.price_eur));
    return { country, x: gx, y: gy, beta: fitLine(gx, gy),
      color: [C.teal, C.orange, C.blue][index], symbol: ['circle', 'square', 'triangle'][index] };
  });
  if (!(pooled[1] > 0) || !groups.every(g => Math.abs(g.beta[1] + 8) < 1e-10)) {
    throw Error('The intended slope reversal is absent.');
  }
  const number = v => Number(v.toFixed(10));
  const slope = `+${pooled[1].toFixed(1)}`;
  const notes = `Original, deliberately constructed synthetic data, not observations from real countries. `
    + `One point is one hotel. Price is EUR per night; distance is kilometres from its city centre. `
    + `There are eight hotels in each fictional country A, B and C. Country mean distances are 3, 6 and 9 km; mean prices are 70, 120 and 170 EUR. `
    + `Data source: data/raw/simpson_hotels.csv, generated by make_simpson_hotels() in src/dataviz_course/synthetic_data.py. `
    + `The one-intercept pooled OLS coefficients are ${JSON.stringify(pooled)}. `
    + `Country-specific fits are ${JSON.stringify(groups.map(g => ({country:g.country,beta:g.beta})))}. `
    + `The equal group slopes mean a joint regression with three country intercepts and a common distance coefficient also has slope -8. `
    + `This is a finite constructed illustration, not a statistical uncertainty or causal-inference exercise. `
    + `Conceptual reference: Kievit, Frankenhuis, Waldorp and Borsboom (2013), Simpson's paradox in psychological science: a practical guide, Figure 1 and discussion. ${source} `
    + `No data or artwork from that article is reproduced.`;

  function text(s, name, value, left, top, width, height, size = 28, color = C.ink, bold = false) {
    const t = s.shapes.add({name, geometry:'textbox',
      position:{left,top,width,height}, fill:'none', line:{fill:'none',width:0}});
    t.text = value;
    t.text.style = {typeface:'Arial',fontSize:size,color,bold,insets:0,
      verticalAlignment:'middle',autoFit:'none'};
    return t;
  }
  function slide(title, guidance) {
    const s = presentation.slides.add();
    s.background.fill = C.paper;
    text(s,'title',title,72,44,1136,70,43,C.ink,true);
    text(s,'synthetic-disclosure','Synthetic illustration: 24 hotels in three fictional countries',
      72,669,1136,30,19,C.muted);
    s.speakerNotes.text = `${guidance}\n\n${notes}`;
    return s;
  }
  function chart(s, grouped) {
    const series = [{name:'Pooled fit', xValues:[1,11],
      values:[1,11].map(v=>number(pooled[0]+pooled[1]*v)),
      line:{fill:grouped ? C.axis : C.ink,width:2.5},
      marker:{symbol:'circle',size:2,fill:grouped ? C.axis : C.ink},
      dataLabelOverrides:[{idx:1,text:'Pooled',position:'top',showValue:false,
        textStyle:{fontSize:19,fill:C.muted}}]}];
    if (grouped) {
      for (const g of groups) {
        const ends = [Math.min(...g.x),Math.max(...g.x)];
        series.push({name:`Country ${g.country} fit`,xValues:ends,
          values:ends.map(v=>number(g.beta[0]+g.beta[1]*v)),
          line:{fill:g.color,width:3},marker:{symbol:'none'}});
        series.push({name:`Country ${g.country} hotels`,xValues:g.x,values:g.y,
          line:{fill:'none',width:0},marker:{symbol:g.symbol,size:9,fill:g.color},
          dataLabelOverrides:[{idx:7,text:`Country ${g.country}`,position:'bottom',showValue:false,
            textStyle:{fontSize:21,fill:g.color,bold:true}}]});
      }
    } else {
      series.push({name:'Hotels',xValues:x,values:y,
        line:{fill:'none',width:0},marker:{symbol:'circle',size:9,fill:C.ink}});
    }
    const c = s.charts.add('scatter',{
      name:grouped ? 'Hotel prices, country-specific fits and pooled fit' : 'Hotel prices and pooled fit',
      position:{left:62,top:155,width:738,height:470},series,
      scatterOptions:{style:'lineWithMarkers'},hasLegend:false,chartFill:C.paper,plotAreaFill:C.paper,
      xAxis:{title:'Distance from city centre (km)',min:0,max:12,majorUnit:3,numberFormatCode:'0',
        textStyle:{fontSize:19,fill:C.muted},line:{fill:C.axis,width:1},majorGridlines:null},
      yAxis:{title:'Price per night (EUR)',min:0,max:220,majorUnit:50,numberFormatCode:'0',
        textStyle:{fontSize:19,fill:C.muted},line:{fill:C.axis,width:1},majorGridlines:null},
    });
    applyPresentationChartFont(c,{fontFamily:'Arial'});
  }
  {
    const s = slide('Hotel prices and distance',
      'Show the pooled chart before revealing country membership. Ask students what direction the fitted association has. '
      + 'Invite an interpretation, then ask whether they would expect the same relationship within every country. '
      + 'The dots already form clusters: students may notice this before the colour reveal. Welcome that observation. '
      + 'The line uses every hotel, not only country averages.');
    chart(s,false);
    text(s,'pooled-heading','One line for all hotels',830,205,380,78,32,C.ink,true);
    text(s,'pooled-slope',`Slope: ${slope} EUR/km`,830,305,380,52,30);
    text(s,'prediction-prompt','Would the same pattern\nhold within each country?',830,425,380,132,31,C.teal);
  }
  {
    const s = slide('Within every country, the slope is negative',
      'Reveal country colours, marker shapes and fitted lines. Keep all observations, positions, axes and units unchanged. '
      + 'The grey pooled line is exactly the line from the previous slide. Ask students to explain the reversal before naming it. '
      + 'Each country fit has slope -8 EUR/km. Country C has higher average distance and higher average price than country B, '
      + 'which in turn has higher averages than country A. Those differences outweigh the negative associations within countries.');
    chart(s,true);
    text(s,'within-heading','Same hotels.\nSame axes.',830,201,380,98,32,C.ink,true);
    text(s,'within-slope','Within each country:\n−8 EUR per extra km',830,340,380,105,30,C.teal);
    text(s,'reversal-prompt','What made the pooled\nline slope upwards?',830,503,380,104,29);
  }
  {
    const s = slide('Simpson’s paradox',
      'The positive pooled and negative within-country associations are both properties of this same dataset. '
      + 'Adding country intercepts changes the comparison to within-country variation. A common slope is sufficient here '
      + 'because the constructed country slopes are identical; other datasets may need different slopes as well. '
      + 'Do not teach that including every available grouping variable is always correct, or that either line alone identifies causation. '
      + 'The research question and knowledge about the data determine the relevant comparison. '
      + 'Connect to purpose: simplifying away country membership would hide information essential to a within-country question. '
      + 'No regression derivation is required.');
    chart(s,true);
    text(s,'pooled-model',`One intercept\nSlope: ${slope} EUR/km`,830,177,380,105,29);
    text(s,'country-model','Separate country intercepts\nCommon slope: −8 EUR/km',830,309,380,112,28,C.teal);
    text(s,'between-explanation','Countries with higher average\ndistance also have higher\naverage prices.',830,454,380,115,26);
    text(s,'causal-caution','Neither fit alone establishes causation.',830,598,380,44,20,C.muted);
  }
  return {pooled,groups:groups.map(g=>({country:g.country,beta:g.beta}))};
}
